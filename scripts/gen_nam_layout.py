#!/usr/bin/env python3
"""Writes Sources/IRCaptureCore/NAMLayout.swift from reference/nam_v3_layout.json (run after changing the JSON)."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
L = json.loads((root / "reference/nam_v3_layout.json").read_text())
env = L["env_db"]
rows = [", ".join(str(v) for v in env[i:i + 32]) for i in range(0, len(env), 32)]
out = f"""// Generated by scripts/gen_nam_layout.py from reference/nam_v3_layout.json. Don't edit by hand.
// Layout of NAM's v3 training signal (TONE3000's T3K-sweep-v3.wav) and its 10 ms envelope in dB.
enum NAMLayout {{
    static let name = {json.dumps(L["name"])}
    static let length = {L["length"]}
    static let blips = [{L["blips"][0]}, {L["blips"][1]}]
    static let validationLength = {L["validation_length"]}
    static let firstSound = {L["first_sound"]}
    static let lastSound = {L["last_sound"]}
    static let envBlock = {L["env_block"]}
    static let envDB: [Double] = [
        {(",\n        ").join(rows)}
    ]
}}
"""
(root / "Sources/IRCaptureCore/NAMLayout.swift").write_text(out)
print("wrote NAMLayout.swift,", len(env), "envelope values")
